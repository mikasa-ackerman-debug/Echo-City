import type { CardSuit } from "@echo/protocol";

/**
 * 试炼卡图鉴（完整卡库）。所有 48 张卡 + Joker 的展示元数据。
 * 已实现的卡以 `@echo/engine` 的 `TrialDef` 为规则权威来源；
 * 未实现的卡以本文件的 `rules` 字段为规则文本。
 */

export interface CardMeta {
  suit: CardSuit;
  rank: number;
  name: string;
  story: string;
  tests: string;
  players: string;
  rules: string;
  pass: string;
  fail: string;
  gatekeeper?: string;
  status: "implemented" | "planned" | "new";
}

export function cardMetaId(suit: CardSuit, rank: number): string {
  const s = { "♦": "diamond", "♥": "heart", "♣": "club", "♠": "spade" }[suit as string] ?? "joker";
  const r = rank === 0 ? "joker" : rank === 11 ? "J" : rank === 12 ? "Q" : rank === 13 ? "K" : String(rank);
  return s === "joker" ? "joker" : `${s}-${r}`;
}

