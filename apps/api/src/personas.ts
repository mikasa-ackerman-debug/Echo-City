/** Get a persona template by id. */
export function getPersonaTemplate(id: string): PersonaTemplate | undefined {
  return PERSONA_TEMPLATES.find((p) => p.id === id);
}

/** List all persona summaries (for the UI). */
export function listPersonaSummaries() {
  return PERSONA_TEMPLATES.map((p) => ({
    id: p.id,
    name: p.name,
    tagline: p.tagline,
    traits: p.traits,
    suits: p.preference.suits.join(""),
    description: p.preference.description,
  }));
}
